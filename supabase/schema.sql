-- ---------------------------------------------------------------------
-- 1. TURMAS (contas / assinaturas)
--    Uma linha por turma. "user" é o login e também o turma_id usado
--    nas outras tabelas. ("user" é palavra reservada: sempre entre aspas.)
-- ---------------------------------------------------------------------
create table if not exists public.batecontroleusers (
  "user"          text primary key,                     -- nome da turma (login), sempre minúsculo
  pass            text not null,                        -- senha (texto puro — veja "Segurança" no README)
  whatsapp        text,                                 -- WhatsApp do líder, só números com DDD
  indicado_por    text default 'Nenhum',                -- turma que indicou ("Nenhum" = veio direto)
  criacao         timestamptz not null default now(),   -- data do cadastro
  data_expiracao  timestamptz,                          -- até quando o acesso está liberado
  status          text not null default 'gratis',       -- 'gratis' (teste) ou 'pago' (assinante)
  observacao      text,                                 -- anotações internas do painel master
  ultimo_acesso   timestamptz                           -- atualizado a cada entrada no sistema
);

-- colunas novas do painel master (para bancos que já existiam)
alter table public.batecontroleusers add column if not exists observacao    text;
alter table public.batecontroleusers add column if not exists ultimo_acesso timestamptz;

create index if not exists batecontroleusers_indicado_idx  on public.batecontroleusers (lower(indicado_por));
create index if not exists batecontroleusers_expiracao_idx on public.batecontroleusers (data_expiracao);


-- ---------------------------------------------------------------------
-- 2. COMPONENTES (quem sai na turma)
-- ---------------------------------------------------------------------
create table if not exists public.componentes (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  turma_id     text not null,                 -- = batecontroleusers."user"
  nome         text not null,
  telefone     text,                          -- WhatsApp, só números com DDD
  valor_total  numeric(10,2) not null default 0,   -- valor da fantasia
  valor_pago   numeric(10,2) not null default 0,   -- total já pago
  vencimento   date                           -- próxima parcela
);

create index if not exists componentes_turma_idx on public.componentes (turma_id);


-- ---------------------------------------------------------------------
-- 3. CUSTOS EXTRAS (divididos entre todos os componentes)
-- ---------------------------------------------------------------------
create table if not exists public.extras (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  turma_id    text not null,
  descricao   text not null,
  valor       numeric(10,2) not null default 0
);

create index if not exists extras_turma_idx on public.extras (turma_id);


-- ---------------------------------------------------------------------
-- 4. DESPESAS (o que já saiu do caixa)
-- ---------------------------------------------------------------------
create table if not exists public.gastos_manuais (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  turma_id     text not null,
  item         text not null,
  valor        numeric(10,2) not null default 0,
  responsavel  text
);

create index if not exists gastos_manuais_turma_idx on public.gastos_manuais (turma_id);


-- ---------------------------------------------------------------------
-- 5. PERMISSÕES (RLS)
--
-- O sistema hoje entra no banco com a chave pública (anon), sem login
-- do Supabase Auth. Para ele funcionar, as políticas abaixo liberam
-- leitura e escrita para a chave anon — é o mesmo comportamento que o
-- projeto já tem hoje.
--
-- ATENÇÃO: isso significa que qualquer pessoa com a chave anon (que fica
-- no código do site) consegue ler e alterar os dados. Para fechar de
-- verdade é preciso migrar o login para o Supabase Auth e trocar estas
-- políticas por regras por turma (veja o README, seção "Segurança").
-- ---------------------------------------------------------------------
alter table public.batecontroleusers enable row level security;
alter table public.componentes       enable row level security;
alter table public.extras            enable row level security;
alter table public.gastos_manuais    enable row level security;

do $$
declare t text;
begin
  foreach t in array array['batecontroleusers', 'componentes', 'extras', 'gastos_manuais'] loop
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'acesso_app_anon') then
      execute format('create policy acesso_app_anon on public.%I for all to anon, authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;


